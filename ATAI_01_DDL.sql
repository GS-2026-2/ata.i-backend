-- =====================================================================
-- ATA.I - Copiloto de gestao escolar
-- Global Solution CitizenTech | Database Design
-- Script 1/3 - D.D.L. (CREATE TABLE e ALTER TABLE)
-- SGBD: Oracle Database 19c ou superior
-- =====================================================================
-- Derivado EXCLUSIVAMENTE do diagrama de classes UML do ATA.I:
--   Escola, Usuario, Reuniao, Ata, AlteracaoPrioridade, PrioridadeAnual
--   Enums: TipoUsuario, StatusAta, OperacaoPrioridade
-- Decisoes de modelagem aprovadas:
--   D1 Reuniao.criadaPor  -> id_usuario_criador (associacao "cria")
--   D2 Ata.aprovadaPor    -> id_usuario_aprovador (associacao "aprova ou confirma")
--   D3 REMOVER desativa a prioridade (st_ativa = 'N'), sem exclusao fisica
--   D4 INCLUIR nasce sem prioridade; o vinculo e criado na aprovacao da ata
-- O historico de cada prioridade e obtido pelas alteracoes de atas APROVADAS.
-- ---------------------------------------------------------------------
-- Ordem de execucao: ATAI_01_DDL.sql -> ATAI_02_DML.sql -> ATAI_03_DQL.sql
-- Convencao de nomes: tabelas T_ATAI_*, PK_ (chave primaria),
-- FK_ (chave estrangeira), UK_ (unica), CK_ (verificacao), IX_ (indice).
-- Prefixos de coluna: id_ (identificador), nm_ (nome), ds_ (descricao/texto),
-- dt_ (data/instante), nr_ (numero), tp_ (tipo), st_ (status/flag S/N).
-- Mapeamento Java: boolean -> CHAR(1) 'S'/'N'; Instant -> TIMESTAMP (UTC);
-- LocalDate -> DATE; enum -> VARCHAR2 com CHECK; Long -> NUMBER(10) IDENTITY.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 0. Limpeza: remove as tabelas se ja existirem (permite reexecutar)
--    Inclui nomes da versao anterior do modelo.
-- ---------------------------------------------------------------------
BEGIN
    FOR t IN (SELECT table_name
                FROM user_tables
               WHERE table_name IN ('T_ATAI_ALTERACAO_PRIORIDADE',
                                    'T_ATAI_PRIORIDADE_ANUAL',
                                    'T_ATAI_ATA',
                                    'T_ATAI_REUNIAO',
                                    'T_ATAI_USUARIO',
                                    'T_ATAI_ESCOLA',
                                    -- versao anterior (fora do diagrama)
                                    'T_ATAI_DESPESA',
                                    'T_ATAI_HISTORICO_PRIORIDADE',
                                    'T_ATAI_PROPOSTA_ALTERACAO',
                                    'T_ATAI_PRIORIDADE',
                                    'T_ATAI_PARTICIPANTE',
                                    'T_ATAI_LISTA_PRIORIDADE')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/


-- =====================================================================
-- 1. CREATE TABLE (colunas, NOT NULL, DEFAULT e chave primaria)
-- =====================================================================

-- Escola publica que utiliza o ATA.I
CREATE TABLE T_ATAI_ESCOLA (
    id_escola           NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY,
    nm_escola           VARCHAR2(120)   NOT NULL,
    st_ativa            CHAR(1)         DEFAULT 'S' NOT NULL,
    dt_criacao          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ATAI_ESCOLA PRIMARY KEY (id_escola)
);

-- Usuarios do sistema. Escola obrigatoria para perfis escolares;
-- SUPERADMIN nao pertence a escola (acesso administrativo global).
CREATE TABLE T_ATAI_USUARIO (
    id_usuario          NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY,
    id_escola           NUMBER(10),
    nm_usuario          VARCHAR2(100)   NOT NULL,
    ds_email            VARCHAR2(120)   NOT NULL,
    ds_senha_hash       VARCHAR2(255)   NOT NULL,
    tp_usuario          VARCHAR2(15)    NOT NULL,
    st_ativo            CHAR(1)         DEFAULT 'S' NOT NULL,
    dt_criacao          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ATAI_USUARIO PRIMARY KEY (id_usuario)
);

-- Reuniao registrada por diretor ou coordenador para um ano de referencia.
-- Transcricao opcional quando e enviada uma ata pronta.
CREATE TABLE T_ATAI_REUNIAO (
    id_reuniao          NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY,
    id_escola           NUMBER(10)      NOT NULL,
    id_usuario_criador  NUMBER(10)      NOT NULL,
    ds_titulo           VARCHAR2(150)   NOT NULL,
    dt_reuniao          DATE            NOT NULL,
    nr_ano_referencia   NUMBER(4)       NOT NULL,
    ds_transcricao      CLOB,
    dt_criacao          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ATAI_REUNIAO PRIMARY KEY (id_reuniao)
);

-- Ata da reuniao (minuta ou ata pronta) e sua aprovacao pelo diretor
CREATE TABLE T_ATAI_ATA (
    id_ata                  NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY,
    id_reuniao              NUMBER(10)      NOT NULL,
    id_usuario_aprovador    NUMBER(10),
    ds_texto                CLOB            NOT NULL,
    st_ata                  VARCHAR2(10)    DEFAULT 'MINUTA' NOT NULL,
    dt_criacao              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    dt_aprovacao            TIMESTAMP,
    CONSTRAINT PK_ATAI_ATA PRIMARY KEY (id_ata)
);

-- Prioridade anual da escola. Mantem o identificador entre reunioes.
CREATE TABLE T_ATAI_PRIORIDADE_ANUAL (
    id_prioridade       NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY,
    id_escola           NUMBER(10)      NOT NULL,
    nr_ano_referencia   NUMBER(4)       NOT NULL,
    ds_prioridade       VARCHAR2(500)   NOT NULL,
    nr_ordem            NUMBER(3)       NOT NULL,
    st_ativa            CHAR(1)         DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_ATAI_PRIORIDADE_ANUAL PRIMARY KEY (id_prioridade)
);

-- Alteracao de prioridade registrada em uma ata (composicao Ata 1:N).
-- Pendente enquanto a ata e MINUTA; aplicada na aprovacao.
CREATE TABLE T_ATAI_ALTERACAO_PRIORIDADE (
    id_alteracao        NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY,
    id_ata              NUMBER(10)      NOT NULL,
    id_prioridade       NUMBER(10),
    tp_operacao         VARCHAR2(10)    NOT NULL,
    ds_proposta         VARCHAR2(500),
    nr_ordem_proposta   NUMBER(3),
    ds_justificativa    VARCHAR2(1000),
    ds_trecho_origem    VARCHAR2(2000),
    CONSTRAINT PK_ATAI_ALTERACAO_PRIORIDADE PRIMARY KEY (id_alteracao)
);


-- =====================================================================
-- 2. ALTER TABLE - chaves estrangeiras (relacionamentos)
-- =====================================================================

-- Escola 1 : 0..* Usuario ("vincula")
ALTER TABLE T_ATAI_USUARIO ADD CONSTRAINT FK_ATAI_USUARIO_ESCOLA
    FOREIGN KEY (id_escola) REFERENCES T_ATAI_ESCOLA (id_escola);

-- Escola 1 : 0..* Reuniao ("registra")
ALTER TABLE T_ATAI_REUNIAO ADD CONSTRAINT FK_ATAI_REUNIAO_ESCOLA
    FOREIGN KEY (id_escola) REFERENCES T_ATAI_ESCOLA (id_escola);

-- Usuario 1 : 0..* Reuniao ("cria")
ALTER TABLE T_ATAI_REUNIAO ADD CONSTRAINT FK_ATAI_REUNIAO_CRIADOR
    FOREIGN KEY (id_usuario_criador) REFERENCES T_ATAI_USUARIO (id_usuario);

-- Reuniao 1 : 0..1 Ata ("gera ou recebe")
ALTER TABLE T_ATAI_ATA ADD CONSTRAINT FK_ATAI_ATA_REUNIAO
    FOREIGN KEY (id_reuniao) REFERENCES T_ATAI_REUNIAO (id_reuniao);

-- Usuario 0..1 : 0..* Ata ("aprova ou confirma")
ALTER TABLE T_ATAI_ATA ADD CONSTRAINT FK_ATAI_ATA_APROVADOR
    FOREIGN KEY (id_usuario_aprovador) REFERENCES T_ATAI_USUARIO (id_usuario);

-- Escola 1 : 0..* PrioridadeAnual ("possui")
ALTER TABLE T_ATAI_PRIORIDADE_ANUAL ADD CONSTRAINT FK_ATAI_PRIORIDADE_ESCOLA
    FOREIGN KEY (id_escola) REFERENCES T_ATAI_ESCOLA (id_escola);

-- Ata 1 : 0..* AlteracaoPrioridade ("registra", composicao)
ALTER TABLE T_ATAI_ALTERACAO_PRIORIDADE ADD CONSTRAINT FK_ATAI_ALTERACAO_ATA
    FOREIGN KEY (id_ata) REFERENCES T_ATAI_ATA (id_ata) ON DELETE CASCADE;

-- PrioridadeAnual 0..1 : 0..* AlteracaoPrioridade ("recebe alteracoes")
ALTER TABLE T_ATAI_ALTERACAO_PRIORIDADE ADD CONSTRAINT FK_ATAI_ALTERACAO_PRIORIDADE
    FOREIGN KEY (id_prioridade) REFERENCES T_ATAI_PRIORIDADE_ANUAL (id_prioridade);


-- =====================================================================
-- 3. ALTER TABLE - restricoes de unicidade (UNIQUE)
-- =====================================================================

ALTER TABLE T_ATAI_USUARIO ADD CONSTRAINT UK_ATAI_USUARIO_EMAIL
    UNIQUE (ds_email);

-- Cada reuniao gera ou recebe no maximo uma ata
ALTER TABLE T_ATAI_ATA ADD CONSTRAINT UK_ATAI_ATA_REUNIAO
    UNIQUE (id_reuniao);


-- =====================================================================
-- 4. ALTER TABLE - restricoes de verificacao (CHECK / regras de negocio)
-- =====================================================================

ALTER TABLE T_ATAI_ESCOLA ADD CONSTRAINT CK_ATAI_ESCOLA_ATIVA
    CHECK (st_ativa IN ('S', 'N'));

-- Enum TipoUsuario
ALTER TABLE T_ATAI_USUARIO ADD CONSTRAINT CK_ATAI_USUARIO_TIPO
    CHECK (tp_usuario IN ('SUPERADMIN', 'DIRETOR', 'COORDENADOR', 'PROFESSOR'));

ALTER TABLE T_ATAI_USUARIO ADD CONSTRAINT CK_ATAI_USUARIO_ATIVO
    CHECK (st_ativo IN ('S', 'N'));

-- Escola obrigatoria para perfis escolares; proibida para SUPERADMIN
ALTER TABLE T_ATAI_USUARIO ADD CONSTRAINT CK_ATAI_USUARIO_ESCOLA
    CHECK ((tp_usuario = 'SUPERADMIN' AND id_escola IS NULL)
        OR (tp_usuario <> 'SUPERADMIN' AND id_escola IS NOT NULL));

ALTER TABLE T_ATAI_REUNIAO ADD CONSTRAINT CK_ATAI_REUNIAO_ANO
    CHECK (nr_ano_referencia BETWEEN 2000 AND 2100);

-- Enum StatusAta
ALTER TABLE T_ATAI_ATA ADD CONSTRAINT CK_ATAI_ATA_STATUS
    CHECK (st_ata IN ('MINUTA', 'APROVADA'));

-- Ata aprovada tem aprovador e data; minuta nao tem nenhum dos dois
ALTER TABLE T_ATAI_ATA ADD CONSTRAINT CK_ATAI_ATA_APROVACAO
    CHECK ((st_ata = 'APROVADA' AND id_usuario_aprovador IS NOT NULL AND dt_aprovacao IS NOT NULL)
        OR (st_ata = 'MINUTA'   AND id_usuario_aprovador IS NULL     AND dt_aprovacao IS NULL));

ALTER TABLE T_ATAI_PRIORIDADE_ANUAL ADD CONSTRAINT CK_ATAI_PRIORIDADE_ANO
    CHECK (nr_ano_referencia BETWEEN 2000 AND 2100);

ALTER TABLE T_ATAI_PRIORIDADE_ANUAL ADD CONSTRAINT CK_ATAI_PRIORIDADE_ORDEM
    CHECK (nr_ordem > 0);

ALTER TABLE T_ATAI_PRIORIDADE_ANUAL ADD CONSTRAINT CK_ATAI_PRIORIDADE_ATIVA
    CHECK (st_ativa IN ('S', 'N'));

-- Enum OperacaoPrioridade
ALTER TABLE T_ATAI_ALTERACAO_PRIORIDADE ADD CONSTRAINT CK_ATAI_ALTERACAO_OPERACAO
    CHECK (tp_operacao IN ('INCLUIR', 'ATUALIZAR', 'REMOVER'));

-- ATUALIZAR e REMOVER sempre apontam para uma prioridade existente;
-- INCLUIR exige descricao (o vinculo e criado na aprovacao - D4)
ALTER TABLE T_ATAI_ALTERACAO_PRIORIDADE ADD CONSTRAINT CK_ATAI_ALTERACAO_ALVO
    CHECK ((tp_operacao = 'INCLUIR' AND ds_proposta IS NOT NULL)
        OR (tp_operacao IN ('ATUALIZAR', 'REMOVER') AND id_prioridade IS NOT NULL));

ALTER TABLE T_ATAI_ALTERACAO_PRIORIDADE ADD CONSTRAINT CK_ATAI_ALTERACAO_ORDEM
    CHECK (nr_ordem_proposta IS NULL OR nr_ordem_proposta > 0);


-- =====================================================================
-- 5. Indices de apoio as consultas por escola e ano e as FKs
-- =====================================================================

CREATE INDEX IX_ATAI_USUARIO_ESCOLA       ON T_ATAI_USUARIO (id_escola);
CREATE INDEX IX_ATAI_REUNIAO_ESCOLA_ANO   ON T_ATAI_REUNIAO (id_escola, nr_ano_referencia);
CREATE INDEX IX_ATAI_PRIORIDADE_ESC_ANO   ON T_ATAI_PRIORIDADE_ANUAL (id_escola, nr_ano_referencia);
CREATE INDEX IX_ATAI_ALTERACAO_ATA        ON T_ATAI_ALTERACAO_PRIORIDADE (id_ata);
CREATE INDEX IX_ATAI_ALTERACAO_PRIORIDADE ON T_ATAI_ALTERACAO_PRIORIDADE (id_prioridade);


-- =====================================================================
-- 6. Comentarios das tabelas (documentacao no dicionario de dados)
-- =====================================================================

COMMENT ON TABLE T_ATAI_ESCOLA               IS 'Escola publica que utiliza o ATA.I';
COMMENT ON TABLE T_ATAI_USUARIO              IS 'Usuarios e perfis (SUPERADMIN sem escola)';
COMMENT ON TABLE T_ATAI_REUNIAO              IS 'Reunioes por escola e ano de referencia';
COMMENT ON TABLE T_ATAI_ATA                  IS 'Ata da reuniao (minuta ou ata pronta) e aprovacao do diretor';
COMMENT ON TABLE T_ATAI_PRIORIDADE_ANUAL     IS 'Prioridades anuais da escola';
COMMENT ON TABLE T_ATAI_ALTERACAO_PRIORIDADE IS 'Alteracoes de prioridade registradas em cada ata';
